import type { ExampleDefinition } from '../../../docs-meta/examples';
import type {
  ExampleSourceFile,
  ExampleSourceManifest,
  HighlightedExampleSource,
} from './example-source-types';

const base = '/mapseekai/emap/examples/';
const github = 'https://github.com/mapseekai/emap/blob/master/';
const languageNames = {
  html: 'HTML',
  javascript: 'JavaScript',
  typescript: 'TypeScript',
  css: 'CSS',
  json: 'JSON',
};

function node<K extends keyof HTMLElementTagNameMap>(
  root: Document,
  tag: K,
  className: string,
  text?: string,
) {
  const element = root.createElement(tag);
  element.className = className;
  if (text !== undefined) element.textContent = text;
  return element;
}

/** Read-only source viewer. Formatting and syntax highlighting are generated by Vite. */
export function renderExampleSource(
  root: Document,
  pane: HTMLElement,
  example: ExampleDefinition,
): () => void {
  if (pane.childElementCount) return () => {};
  const controller = new AbortController();
  let currentText = '';
  let revision = 0;
  let disposed = false;
  const cache = new Map<string, Promise<HighlightedExampleSource>>();
  const toolbar = node(root, 'div', 'example-code-toolbar');
  const fileTabs = node(root, 'div', 'example-source-tabs');
  fileTabs.setAttribute('role', 'tablist');
  fileTabs.setAttribute('aria-label', '源码文件');
  const copy = node(root, 'button', 'example-copy-code', '复制代码');
  copy.type = 'button';
  copy.disabled = true;
  const status = node(root, 'span', 'example-copy-status');
  status.setAttribute('role', 'status');
  const link = node(root, 'a', 'example-source-github', '在 GitHub 查看');
  link.href = github + example.source.html;
  toolbar.append(fileTabs, status, copy, link);
  const meta = node(root, 'div', 'example-source-meta');
  const path = node(root, 'span', 'example-source-path');
  const details = node(root, 'span', 'example-source-details');
  meta.append(path, details);
  const viewport = node(root, 'div', 'example-source-code');
  viewport.id = 'example-source-code';
  viewport.tabIndex = 0;
  viewport.setAttribute('role', 'tabpanel');
  viewport.setAttribute('aria-busy', 'true');
  viewport.textContent = '正在读取源码…';
  pane.append(toolbar, meta, viewport);

  copy.addEventListener('click', () => {
    const text = currentText;
    void (async () => {
      try {
        const clipboard = root.defaultView?.navigator.clipboard;
        if (!clipboard) throw new Error('Clipboard unavailable');
        await clipboard.writeText(text);
        if (!disposed && currentText === text) status.textContent = '已复制';
      } catch {
        if (!disposed && currentText === text) status.textContent = '请选中代码手动复制';
      }
    })();
  });

  async function readJson<T>(url: string): Promise<T> {
    const response = await fetch(url, { signal: controller.signal });
    if (!response.ok) throw new Error(`Source request failed (${response.status})`);
    return response.json() as Promise<T>;
  }

  async function showFile(file: ExampleSourceFile, button: HTMLButtonElement) {
    const request = ++revision;
    copy.disabled = true;
    currentText = '';
    status.textContent = '';
    path.textContent = file.path;
    path.title = file.path;
    details.textContent = `${languageNames[file.language]} · ${file.lineCount} 行`;
    link.href = github + file.origin;
    viewport.setAttribute('aria-labelledby', button.id);
    viewport.setAttribute('aria-busy', 'true');
    for (const tab of fileTabs.querySelectorAll<HTMLButtonElement>('button')) {
      const selected = tab === button;
      tab.setAttribute('aria-selected', String(selected));
      tab.tabIndex = selected ? 0 : -1;
    }
    viewport.textContent = '正在读取源码…';
    let pending = cache.get(file.url);
    if (!pending) {
      pending = readJson<HighlightedExampleSource>(file.url);
      cache.set(file.url, pending);
    }
    try {
      const source = await pending;
      if (disposed || request !== revision) return;
      currentText = source.text;
      viewport.innerHTML = source.html;
      viewport.scrollTop = viewport.scrollLeft = 0;
      copy.disabled = !currentText;
    } catch {
      cache.delete(file.url);
      if (disposed || request !== revision) return;
      viewport.textContent = '无法读取源码，请使用 GitHub 链接。';
    } finally {
      if (!disposed && request === revision) viewport.setAttribute('aria-busy', 'false');
    }
  }

  void (async () => {
    try {
      const manifest = await readJson<ExampleSourceManifest>(
        `${base}sources/${example.id}/manifest.json`,
      );
      if (disposed) return;
      if (!manifest.files.length) throw new Error('Empty source manifest');
      let active: HTMLButtonElement | undefined;
      for (const [index, file] of manifest.files.entries()) {
        const button = node(root, 'button', 'example-source-tab', file.name);
        button.type = 'button';
        button.id = `source-file-${index}`;
        button.dataset.filename = file.id;
        button.title = file.path;
        button.setAttribute('role', 'tab');
        button.setAttribute('aria-controls', viewport.id);
        button.addEventListener('click', () => {
          void showFile(file, button);
        });
        button.addEventListener('keydown', (event) => {
          if (!['ArrowLeft', 'ArrowRight', 'Home', 'End'].includes(event.key)) return;
          event.preventDefault();
          const buttons = Array.from(fileTabs.querySelectorAll<HTMLButtonElement>('button'));
          const target =
            event.key === 'Home'
              ? 0
              : event.key === 'End'
                ? buttons.length - 1
                : (index + (event.key === 'ArrowRight' ? 1 : buttons.length - 1)) % buttons.length;
          buttons[target].click();
          buttons[target].focus();
          buttons[target].scrollIntoView?.({ block: 'nearest', inline: 'nearest' });
        });
        fileTabs.append(button);
        if (file.id === manifest.defaultFile) active = button;
      }
      (active ?? fileTabs.querySelector<HTMLButtonElement>('button'))!.click();
    } catch {
      if (disposed) return;
      let original = '';
      try {
        const embedded: unknown = JSON.parse(
          root.getElementById('emap-example-source')?.textContent ?? 'null',
        );
        if (typeof embedded === 'string') original = embedded;
      } catch {
        /* Keep the GitHub link available for unavailable source assets. */
      }
      viewport.replaceChildren(
        node(root, 'pre', '', original || '无法读取源码，请使用 GitHub 链接。'),
      );
      viewport.setAttribute('aria-label', '完整 HTML');
      viewport.setAttribute('aria-busy', 'false');
      path.textContent = example.source.html;
      status.textContent = original ? '已显示原始 HTML' : '';
      currentText = original;
      copy.disabled = !original;
    }
  })();
  return () => {
    disposed = true;
    revision++;
    controller.abort();
  };
}
